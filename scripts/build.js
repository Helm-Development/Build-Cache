'use strict';
// Bundles src/actions.js and its dependencies with @vercel/ncc into
// dist/lib/index.js, and writes the four small entry files that GitHub runs:
//
//   dist/restore/index.js       main step of the action
//   dist/save/index.js          post step of the action
//   dist/restore-only/index.js  the restore sub-action
//   dist/save-only/index.js     the save sub-action
//
// dist/ is committed, because GitHub runs an action's files as they are in
// the repository at the tag a workflow names.
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const dist = path.join(root, 'dist');
const ncc = path.join(root, 'node_modules', '@vercel', 'ncc', 'dist', 'ncc', 'cli.js');

fs.rmSync(dist, { recursive: true, force: true });
execFileSync(process.execPath, [ncc, 'build', path.join(root, 'src', 'actions.js'),
  '-o', path.join(dist, 'lib'), '--license', 'licenses.txt', '--quiet'], { stdio: 'inherit' });

const entries = {
  restore: ['Main step of Helm-Development/Build-Cache: restore the cache.', 'restore()'],
  save: ['Post step of Helm-Development/Build-Cache: save the cache when the main step found no entry for the exact key.', "save({ mode: 'post' })"],
  'restore-only': ['Helm-Development/Build-Cache/restore: restore only, never save.', 'restore()'],
  'save-only': ['Helm-Development/Build-Cache/save: save, wherever the step is placed.', "save({ mode: 'save-only' })"],
};
for (const [name, [comment, call]] of Object.entries(entries)) {
  fs.mkdirSync(path.join(dist, name), { recursive: true });
  fs.writeFileSync(path.join(dist, name, 'index.js'),
    `'use strict';\n// ${comment}\n// Generated by scripts/build.js.\nrequire('../lib/index.js').${call};\n`);
}
